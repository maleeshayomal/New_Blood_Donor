"""
Synthetic Dataset Generator Module
===================================
Academic AI Decision-Support Prototype

Generates >= 1,200 synthetic donor records with realistic relationships and
probabilistic response outcomes for training and testing the emergency blood
donor recommendation model.

DISCLAIMER:
All data generated by this module is purely synthetic/demo data for academic purposes.
No real patient or donor personal health information (PHI) is included.
"""

