def save_and_init_db(data_dir: str = "data", db_path: str = "data/blood_donor.db") -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Generate datasets, save to CSV, and initialize SQLite database.
    """
    os.makedirs(data_dir, exist_ok=True)
    
    # 1. Generate synthetic donors (1,400 records)
    donors_df = generate_synthetic_donors(num_records=1400, seed=42)
    donors_csv_path = os.path.join(data_dir, "donors.csv")
    donors_df.to_csv(donors_csv_path, index=False)
    print(f" Saved {len(donors_df)} synthetic donor records to '{donors_csv_path}'")
    
    # 2. Generate sample requests
    requests_df = generate_sample_emergency_requests()
    requests_csv_path = os.path.join(data_dir, "emergency_requests.csv")
    requests_df.to_csv(requests_csv_path, index=False)
    print(f" Saved sample emergency requests to '{requests_csv_path}'")
    
    # 3. Create SQLite Database and tables
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    # Create donors table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS donors (
        donor_id TEXT PRIMARY KEY,
        blood_group TEXT NOT NULL,
        age INTEGER,
        gender TEXT,
        city TEXT,
        latitude REAL,
        longitude REAL,
        available INTEGER,
        donation_count INTEGER,
        days_since_last_donation INTEGER,
        previous_requests INTEGER,
        previous_responses INTEGER,
        response_rate REAL,
        contacted_before INTEGER,
        target_response INTEGER
    )
    """)
    
    # Create emergency_requests table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS emergency_requests (
        request_id TEXT PRIMARY KEY,
        required_blood_group TEXT NOT NULL,
        hospital TEXT NOT NULL,
        latitude REAL,
        longitude REAL,
        units_required INTEGER,
        priority TEXT,
        request_date TEXT,
        notes TEXT
    )
    """)
    
    # Create donation_history table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS donation_history (
        donation_id INTEGER PRIMARY KEY AUTOINCREMENT,
        donor_id TEXT,
        donation_date TEXT,
        response INTEGER,
        request_id TEXT,
        FOREIGN KEY (donor_id) REFERENCES donors (donor_id)
    )
    """)
    
    # Create predictions table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS predictions (
        prediction_id INTEGER PRIMARY KEY AUTOINCREMENT,
        request_id TEXT,
        donor_id TEXT,
        response_probability REAL,
        recommendation_score REAL,
        recommendation_label TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (donor_id) REFERENCES donors (donor_id)
    )
    """)
    
    # Insert or replace donors into SQLite
    donors_df.to_sql("donors", conn, if_exists="replace", index=False)
    requests_df.to_sql("emergency_requests", conn, if_exists="replace", index=False)
    
    conn.commit()
    conn.close()
    print(f" Initialized SQLite database tables in '{db_path}'")
    
    return donors_df, requests_df


if __name__ == "__main__":
    save_and_init_db()
